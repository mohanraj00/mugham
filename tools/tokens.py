#!/usr/bin/env python3
"""Validate the design tokens and write src/tokens/tokens.css from src/tokens/tokens.json."""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'src' / 'tokens' / 'tokens.json'
CSS = ROOT / 'src' / 'tokens' / 'tokens.css'
NAME = re.compile(r'[a-z]+(\.[a-z0-9]+(-[a-z0-9]+)*){1,3}')
# A token value is a short list of CSS words. Only easing tokens accept a function.
# A font stack of the brand needs more than 80 characters, so the limit is 120.
VALUE = re.compile(r'[#a-zA-Z0-9.,/ -]{1,120}')
HEX = re.compile(r'#[0-9a-f]{6}')
UNIT_FRACTION = r'(?:0(?:\.[0-9]{1,4})?|1(?:\.0{1,4})?)'
EASING = re.compile(r'cubic-bezier\(' + ', ?'.join([UNIT_FRACTION] * 4) + r'\)')
COMPACT = {'type.body', 'type.caption', 'space.1', 'space.2', 'space.3', 'space.4',
           'size.column-narrow', 'size.column-medium', 'size.column-wide', 'size.control', 'size.icon', 'size.field'}
DARK_SYSTEM = ':where(:not([data-mu-mode="light"], [data-mu-theme="light"]:not([data-mu-mode])))'
DARK_EXPLICIT = ':where([data-mu-mode="dark"], [data-mu-theme="dark"]:not([data-mu-mode]))'


def load(path=SOURCE):
    return json.loads(Path(path).read_text(encoding='utf-8'))


def css_name(name):
    return '--mu-' + name.replace('.', '-')


def mode_errors(name, value, path):
    if not isinstance(value, dict) or sorted(value) != ['dark', 'light']:
        return [path + ': must have exactly a light value and a dark value']
    found = []
    pattern = EASING if name.startswith('easing.') else VALUE
    for mode in ('light', 'dark'):
        item = value[mode]
        if not isinstance(item, str) or not pattern.fullmatch(item):
            found.append('%s.%s: not a safe CSS value' % (path, mode))
        elif name.startswith('color.') and not HEX.fullmatch(item):
            found.append('%s.%s: a color must be #rrggbb in lower case' % (path, mode))
    return found


def errors(data):
    found = []
    if not isinstance(data, dict) or data.get('format') != 1 or not isinstance(data.get('tokens'), dict):
        return ['(tokens): must be an object with format 1 and tokens']
    seen = set()
    for name, value in data['tokens'].items():
        if not NAME.fullmatch(name):
            found.append(name + ': not a valid token name')
        if css_name(name) in seen:
            found.append(name + ': has the same CSS name as another token')
        seen.add(css_name(name))
        found.extend(mode_errors(name, value, name))
    high_contrast = data.get('high-contrast', {})
    if not isinstance(high_contrast, dict):
        found.append('high-contrast: must be an object')
    else:
        for name, item in high_contrast.items():
            path = 'high-contrast.' + name
            if name not in data['tokens'] or not name.startswith('color.'):
                found.append(path + ': not a known color token')
            else:
                found.extend(mode_errors(name, item, path))
    compact = data.get('compact', {})
    if not isinstance(compact, dict):
        return found + ['compact: must be an object']
    for name, item in compact.items():
        if name not in COMPACT or name not in data['tokens']:
            found.append('compact.%s: not a density token' % name)
        elif not isinstance(item, str) or not VALUE.fullmatch(item):
            found.append('compact.%s: not a safe CSS value' % name)
    return found


def luminance(color):
    channels = [int(color[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    linear = [c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
    return 0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2]


def contrast(front, back):
    high, low = sorted([luminance(front), luminance(back)], reverse=True)
    return (high + 0.05) / (low + 0.05)


def block(selector, values, indent='', scheme=None):
    lines = [indent + selector + ' {']
    if scheme:
        lines.append(indent + '  color-scheme: ' + scheme + ';')
    lines += ['%s  %s: %s;' % (indent, css_name(name), value) for name, value in sorted(values.items())]
    return lines + [indent + '}']


def palette(selector, values, set_scheme=False):
    light = {name: value['light'] for name, value in values.items()}
    dark = {name: value['dark'] for name, value in values.items() if value['light'] != value['dark']}
    scheme = 'dark' if set_scheme else None
    lines = block(selector, light, scheme='light' if set_scheme else None)
    lines += ['@media (prefers-color-scheme: dark) {']
    lines += block(selector + DARK_SYSTEM, dark, '  ', scheme)
    lines += ['}']
    lines += block(selector + DARK_EXPLICIT, dark, scheme=scheme)
    return lines


def css(data):
    lines = ['/* Written by tools/tokens.py from tokens.json. Do not edit this file. */']
    lines += palette(':root', data['tokens'], set_scheme=True)
    if data.get('high-contrast'):
        lines += palette(':root[data-mu-theme="high-contrast"]', data['high-contrast'])
    if data.get('compact'):
        lines += block('[data-mu-density="compact"], :root[data-mu-theme="compact"]', data['compact'])
    lines += ['@media (prefers-reduced-motion: reduce) {', '  :root {']
    lines += ['    %s: 0ms;' % css_name(name) for name in sorted(data['tokens']) if name.startswith('motion.')]
    lines += ['  }', '}']
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true', help='write tokens.css')
    args = parser.parse_args()
    data = load()
    found = errors(data)
    if not found and args.write:
        CSS.write_text(css(data), encoding='utf-8')
    elif not found and CSS.read_text(encoding='utf-8') != css(data):
        found.append('src/tokens/tokens.css does not agree with tokens.json. Run tools/tokens.py --write.')
    print(json.dumps({'passed': not found, 'tokens': len(data.get('tokens', {})), 'errors': found}, indent=2))
    return 1 if found else 0


if __name__ == '__main__':
    sys.exit(main())
