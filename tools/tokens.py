#!/usr/bin/env python3
"""Validate the design tokens and write src/tokens/tokens.css from src/tokens/tokens.json."""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'src' / 'tokens' / 'tokens.json'
CSS = ROOT / 'src' / 'tokens' / 'tokens.css'
NAME = re.compile(r'[a-z]+(\.[a-z0-9]+(-[a-z0-9]+)*){1,3}')
# A token value is a short list of CSS words: colors, lengths, times, weights and font names. No functions
# and no quotes. A font stack of the brand needs more than 80 characters, so the limit is 120.
VALUE = re.compile(r'[#a-zA-Z0-9.,/ -]{1,120}')
HEX = re.compile(r'#[0-9a-f]{6}')


def load(path=SOURCE):
    return json.loads(Path(path).read_text(encoding='utf-8'))


def css_name(name):
    return '--mu-' + name.replace('.', '-')


def errors(data):
    found = []
    if not isinstance(data, dict) or data.get('format') != 1 or not isinstance(data.get('tokens'), dict):
        return ['(tokens): must be an object with format 1 and tokens']
    seen = set()
    for name, value in data['tokens'].items():
        if not NAME.fullmatch(name):
            found.append(name + ': not a valid token name')
        if css_name(name) in seen:
            found.append(name + ': has the same CSS name as another token')
        seen.add(css_name(name))
        if not isinstance(value, dict) or sorted(value) != ['dark', 'light']:
            found.append(name + ': must have exactly a light value and a dark value')
            continue
        for theme in ('light', 'dark'):
            item = value[theme]
            if not isinstance(item, str) or not VALUE.fullmatch(item) or '(' in item:
                found.append('%s.%s: not a safe CSS value' % (name, theme))
            elif name.startswith('color.') and not HEX.fullmatch(item):
                found.append('%s.%s: a color must be #rrggbb in lower case' % (name, theme))
    return found


def luminance(color):
    channels = [int(color[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    linear = [c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
    return 0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2]


def contrast(front, back):
    high, low = sorted([luminance(front), luminance(back)], reverse=True)
    return (high + 0.05) / (low + 0.05)


def block(selector, data, theme, indent=''):
    lines = [indent + selector + ' {']
    lines += ['%s  %s: %s;' % (indent, css_name(name), value[theme]) for name, value in sorted(data['tokens'].items())]
    return lines + [indent + '}']


def css(data):
    dark_only = {'format': 1, 'tokens': {k: v for k, v in data['tokens'].items() if v['light'] != v['dark']}}
    motion = sorted(name for name in data['tokens'] if name.startswith('motion.'))
    lines = ['/* Written by tools/tokens.py from tokens.json. Do not edit this file. */']
    lines += block(':root', data, 'light')
    lines += ['@media (prefers-color-scheme: dark) {']
    lines += block(':root:not([data-mu-theme="light"])', dark_only, 'dark', '  ')
    lines += ['}']
    lines += block(':root[data-mu-theme="dark"]', dark_only, 'dark')
    lines += ['@media (prefers-reduced-motion: reduce) {', '  :root {']
    lines += ['    %s: 0ms;' % css_name(name) for name in motion]
    lines += ['  }', '}']
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true', help='write tokens.css')
    args = parser.parse_args()
    data = load()
    found = errors(data)
    if not found and args.write:
        CSS.write_text(css(data), encoding='utf-8')
    elif not found and CSS.read_text(encoding='utf-8') != css(data):
        found.append('src/tokens/tokens.css does not agree with tokens.json. Run tools/tokens.py --write.')
    print(json.dumps({'passed': not found, 'tokens': len(data.get('tokens', {})), 'errors': found}, indent=2))
    return 1 if found else 0


if __name__ == '__main__':
    sys.exit(main())
